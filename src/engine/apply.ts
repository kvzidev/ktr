const execFileAsync = promisify(execFile);

export interface ApplyOperation {
  type:
    | "created"
    | "skipped"
    | "synced"
    | "merged"
    | "docker"
    | "env"
    | "create"
    | "install"
    | "git";
  target: string;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function deepMergePreservingExisting(
  current: Record<string, unknown>,
  patch: Record<string, unknown>,
): Record<string, unknown> {
  const result: Record<string, unknown> = { ...current };

  for (const [key, patchValue] of Object.entries(patch)) {
    const existingValue = result[key];
    if (isPlainObject(existingValue) && isPlainObject(patchValue)) {
      result[key] = deepMergePreservingExisting(existingValue, patchValue);
    } else if (!(key in result)) {
      result[key] = patchValue;
    }
  }

  return result;
}

export function resolveTemplatesDir(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.resolve(here, "../templates"),
    path.resolve(here, "../../templates"),
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate;
  }
  throw new Error("Could not locate ktr templates directory");
}

function interpolate(template: string, vars: Record<string, string>): string {
  return template.replace(
    /\{\{(\w+)\}\}/g,
    (_, key: string) => vars[key] ?? "",
  );
}

export function formatPackageArg(spec: PackageSpec): string {
  return spec.version ? `${spec.name}@${spec.version}` : spec.name;
}

export class ApplyContext {
  public readonly operations: ApplyOperation[] = [];
  private readonly templatesDir = resolveTemplatesDir();
  private readonly queuedPackages = new Map<string, Set<string>>();

  constructor(
    public readonly cwd: string,
    public readonly dryRun: boolean,
    public readonly noInstall = false,
  ) {}

  async writeIfMissing(relPath: string, content: string) {
    const abs = path.join(this.cwd, relPath);
    try {
      await fs.access(abs);
      this.operations.push({ type: "skipped", target: relPath });
      return { status: "skipped" as const, relPath };
    } catch {
      if (!this.dryRun) {
        await fs.mkdir(path.dirname(abs), { recursive: true });
        await fs.writeFile(abs, content, "utf8");
      }
      this.operations.push({ type: "created", target: relPath });
      return { status: "created" as const, relPath };
    }
  }

  async writeTemplateIfMissing(
    relPath: string,
    templateRelPath: string,
    vars: Record<string, string> = {},
  ) {
    const templateAbs = path.join(this.templatesDir, templateRelPath);
    const raw = await fs.readFile(templateAbs, "utf8");
    const content = Object.keys(vars).length > 0 ? interpolate(raw, vars) : raw;
    return this.writeIfMissing(relPath, content);
  }

  async writeManaged(relPath: string, content: string) {
    const abs = path.join(this.cwd, relPath);
    const header = "// AUTO-GENERATED BY `npx ktr` — DO NOT EDIT MANUALLY\n";
    if (!this.dryRun) {
      await fs.mkdir(path.dirname(abs), { recursive: true });
      await fs.writeFile(abs, header + content, "utf8");
    }
    this.operations.push({ type: "synced", target: relPath });
    return { status: "synced" as const, relPath };
  }

  async mergePackageJson(relPath: string, patch: Record<string, unknown>) {
    const abs = path.join(this.cwd, relPath);
    const raw = await fs.readFile(abs, "utf8").catch(() => "{}");
    const current = JSON.parse(raw) as Record<string, unknown>;
    const merged = deepMergePreservingExisting(current, patch);
    if (!this.dryRun) {
      await fs.mkdir(path.dirname(abs), { recursive: true });
      await fs.writeFile(abs, `${JSON.stringify(merged, null, 2)}\n`, "utf8");
    }
    this.operations.push({ type: "merged", target: relPath });
  }

  async mergeDockerService(
    serviceName: string,
    definition: Record<string, unknown>,
    namedVolumes: string[] = [],
  ) {
    const abs = path.join(this.cwd, "compose.yml");
    const raw = await fs.readFile(abs, "utf8").catch(() => "services: {}\n");
    const doc = YAML.parseDocument(raw);
    let changed = false;

    if (!doc.hasIn(["services", serviceName])) {
      doc.setIn(["services", serviceName], definition);
      changed = true;
    }

    for (const volumeName of namedVolumes) {
      if (!doc.hasIn(["volumes", volumeName])) {
        doc.setIn(["volumes", volumeName], {});
        changed = true;
      }
    }

    if (changed) {
      if (!this.dryRun) {
        await fs.writeFile(abs, doc.toString(), "utf8");
      }
      this.operations.push({
        type: "docker",
        target: `compose.yml:${serviceName}`,
      });
    }
  }

  async appendEnvExample(vars: Record<string, string>) {
    const abs = path.join(this.cwd, ".env.example");
    const existing = await fs.readFile(abs, "utf8").catch(() => "");
    const existingKeys = new Set(
      existing
        .split(/\r?\n/)
        .map((line) => line.split("=")[0]?.trim())
        .filter(Boolean),
    );
    const additions = Object.entries(vars)
      .filter(([key]) => !existingKeys.has(key))
      .map(([key, val]) => `${key}=${val}`);
    if (additions.length > 0) {
      if (!this.dryRun) {
        const prefix = existing && !existing.endsWith("\n") ? "\n" : "";
        await fs.appendFile(abs, `${prefix}${additions.join("\n")}\n`, "utf8");
      }
      this.operations.push({ type: "env", target: ".env.example" });
    }
  }

  async runCreateCli(spec: CreateCliSpec): Promise<void> {
    const absTarget = path.join(this.cwd, spec.targetDir);
    if (existsSync(absTarget)) {
      this.operations.push({ type: "skipped", target: spec.targetDir });
      return;
    }

    if (this.dryRun || this.noInstall) {
      if (spec.fallbackPackage) {
        await this.writeIfMissing(
          spec.fallbackPackage.path,
          `${JSON.stringify({ name: spec.fallbackPackage.name, version: "0.0.1", private: true, type: "module" }, null, 2)}\n`,
        );
      }
      this.operations.push({ type: "create", target: spec.targetDir });
      return;
    }

    await execFileAsync(spec.command, spec.args, { cwd: this.cwd });
    this.operations.push({ type: "create", target: spec.targetDir });
  }

  queuePackages(
    specs: PackageSpec[],
    cfg: Record<string, Record<string, unknown>>,
  ): void {
    for (const spec of specs) {
      if (spec.when && !spec.when(cfg)) continue;
      const target = spec.target ?? ".";
      const mode = spec.dev ? "dev" : "prod";
      const bucketKey = `${target}::${mode}`;
      const existing = this.queuedPackages.get(bucketKey) ?? new Set<string>();
      existing.add(formatPackageArg(spec));
      this.queuedPackages.set(bucketKey, existing);
    }
  }

  async flushPackages(): Promise<void> {
    for (const [bucketKey, pkgSet] of this.queuedPackages.entries()) {
      const [target, mode] = bucketKey.split("::");
      const pkgs = [...pkgSet];
      if (pkgs.length === 0) continue;

      const label = `${target}: ${pkgs.join(", ")}`;
      this.operations.push({ type: "install", target: label });

      if (this.dryRun || this.noInstall) continue;

      const isDev = mode === "dev";
      if (target === ".") {
        await execFileAsync(
          "pnpm",
          ["add", "-w", ...(isDev ? ["-D"] : []), ...pkgs],
          { cwd: this.cwd },
        );
        continue;
      }

      const pkgJsonPath = path.join(this.cwd, target, "package.json");
      let filterName = target;
      if (existsSync(pkgJsonPath)) {
        const parsed = JSON.parse(await fs.readFile(pkgJsonPath, "utf8")) as {
          name?: string;
        };
        if (parsed.name) filterName = parsed.name;
      }

      await execFileAsync(
        "pnpm",
        ["--filter", filterName, "add", ...(isDev ? ["-D"] : []), ...pkgs],
        { cwd: this.cwd },
      );
    }
  }
}

export async function isGitWorkingTreeDirty(cwd: string): Promise<boolean> {
  try {
    const { stdout } = await execFileAsync("git", ["status", "--porcelain"], {
      cwd,
    });
    return stdout.trim().length > 0;
  } catch {
    return false;
  }
}

export async function initGitRepository(
  cwd: string,
  dryRun: boolean,
): Promise<"initialized" | "skipped"> {
  if (existsSync(path.join(cwd, ".git"))) {
    return "skipped";
  }
  if (!dryRun) {
    await fs.mkdir(cwd, { recursive: true });
    await execFileAsync("git", ["init"], { cwd });
  }
  return "initialized";
}

export async function applyPlan(options: {
  cwd: string;
  existing: KfgConfig | null;
  desired: KfgConfig;
  registry: Map<string, ModuleDefinition>;
  dryRun: boolean;
  noInstall?: boolean;
  useGit?: boolean;
}): Promise<{
  finalConfig: KfgConfig;
  autoAdded: string[];
  operations: ApplyOperation[];
}> {
  const {
    cwd,
    existing,
    desired,
    registry,
    dryRun,
    noInstall = false,
    useGit = false,
  } = options;
  const { modulesToApply, autoAdded, finalConfig } = diffConfigs(
    existing,
    desired,
    registry,
  );
  const ctx = new ApplyContext(cwd, dryRun, noInstall);

  for (const mod of modulesToApply) {
    await mod.apply(ctx, finalConfig);
  }

  await ctx.flushPackages();
  await syncBarrels(ctx, finalConfig);

  if (useGit) {
    await ctx.writeTemplateIfMissing(".gitignore", "shared/gitignore");
    const gitStatus = await initGitRepository(cwd, dryRun);
    if (gitStatus === "initialized") {
      ctx.operations.push({ type: "git", target: "git init" });
    }
  }

  if (!dryRun) {
    await fs.mkdir(cwd, { recursive: true });
    await fs.writeFile(
      path.join(cwd, "ktr.kfg"),
      serializeKfg(finalConfig),
      "utf8",
    );
  }
  ctx.operations.push({ type: "synced", target: "ktr.kfg" });

  return {
    finalConfig,
    autoAdded,
    operations: ctx.operations,
  };
}
